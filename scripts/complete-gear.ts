// Completes the gear presets: tier sets from TBC on have no belt, boots or bracers, and some pieces don't exist in a
// version's Wowhead model data. For every version/class/level this checks belt, boots, bracers and gloves and, where
// one is missing, picks the first candidate (own class, then same armor type, then nearby versions) that exists in
// that version's data. Writes src/data/gearFill.ts. Usage: node scripts/complete-gear.ts
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ZamMirror } from "../server/zam.ts";
import { VERSIONS, CLASSES, classesFor, presetFor, racesFor, type VersionId } from "../src/data/characters.ts";
import { CANDIDATES } from "./gear-candidates.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const mirror = new ZamMirror(resolve(ROOT, process.env.MODEL_DIR ?? "data/zam"));
const SLOTS = [6, 8, 9, 10]; // waist, feet, wrists, hands - the order of the candidate lists
const ARMOR: number[][] = [[1, 2, 6], [3, 7, 13], [4, 11, 10, 12], [5, 8, 9]];
const NEAR: Record<VersionId, string[]> = {
  retail: ["mop", "cata", "wrath", "tbc", "classic"],
  forever: ["forever", "classic", "tbc"],
  classic: ["classic", "forever", "tbc"],
  tbc: ["tbc", "classic", "wrath"],
  wrath: ["wrath", "tbc", "cata"],
  cata: ["cata", "wrath", "mop"],
  mop: ["mop", "cata", "wrath"],
};

const cache = new Map<string, boolean>();
async function exists(env: string, slot: number, display: number) {
  const key = `${env}/${slot}/${display}`;
  let ok = cache.get(key);
  if (ok === undefined) {
    ok = (await mirror.get(`modelviewer/${env}/meta/armor/${slot}/${display}.json`)).status === 200;
    if (!ok && slot === 5) ok = (await mirror.get(`modelviewer/${env}/meta/armor/20/${display}.json`)).status === 200;
    cache.set(key, ok);
  }
  return ok;
}

const fill: Record<string, Record<number, Record<string, [number, number][]>>> = {};
const unresolved: string[] = [];
let filled = 0;
for (const v of VERSIONS) {
  const classes = [...new Set(racesFor(v).flatMap((r) => classesFor(v, r)))];
  for (const cls of classes) {
    const sameArmor = ARMOR.find((a) => a.includes(cls)) ?? [cls];
    const donors = [cls, ...sameArmor.filter((c) => c !== cls)];
    for (const level of ["mid", "end"] as const) {
      const preset = presetFor(v, cls, level);
      if (!preset) continue;
      const have = new Map(preset.items.map(([s, d]) => [s === 20 ? 5 : s, d]));
      for (const [i, slot] of SLOTS.entries()) {
        const current = have.get(slot);
        if (current && (await exists(v.env, slot, current))) continue;
        let pick: number | undefined;
        search: for (const key of NEAR[v.id])
          for (const donor of donors)
            for (const d of CANDIDATES[key]?.[donor]?.[level]?.[i] ?? [])
              if (await exists(v.env, slot, d)) {
                pick = d;
                break search;
              }
        const name = `${v.name} ${CLASSES.find((c) => c.id === cls)?.name} ${level} slot ${slot}`;
        if (pick === undefined) unresolved.push(name);
        else {
          ((fill[v.id] ??= {})[cls] ??= {})[level] ??= [];
          fill[v.id][cls][level].push([slot, pick]);
          filled++;
        }
      }
    }
  }
}

const body = JSON.stringify(fill).replace(/"(\w+)":/g, "$1:");
writeFileSync(
  resolve(ROOT, "src/data/gearFill.ts"),
  `// Generated by scripts/complete-gear.ts: belt, boots, bracers and gloves added to (or replacing) preset pieces that
// tier sets lack or that don't exist in a version's model data. [slot, item display id].
import type { VersionId } from "./characters.ts";

// prettier-ignore
export const GEAR_FILL: Partial<Record<VersionId, Record<number, { mid?: [number, number][]; end?: [number, number][] }>>> = ${body};
`,
);
console.log(`Filled ${filled} slots; ${unresolved.length} unresolved`);
for (const u of unresolved) console.log("  " + u);
